                $rowCost    = (float)($tRow['cost'] ?? 0);
                $hasMargin  = ($tRow['selling_price'] !== null && $tRow['cost'] !== null);
                $rowMargin  = $rowSelling - $rowCost;
                $marginStr  = $hasMargin ? number_format($rowMargin, 2) : '-';

                $pdf->Cell(18, 6, $tid, 1, 0, 'L');
                $pdf->Cell(34, 6, $staffStr, 1, 0, 'L');
