        $pdf->Cell(22, 6, 'Staff ID', 1, 0, 'L', true);
        $pdf->Cell(44, 6, 'Staff Name & Role', 1, 0, 'L', true);
        $pdf->Cell(34, 6, 'Department', 1, 0, 'L', true);
        $pdf->Cell(16, 6, 'Present', 1, 0, 'C', true);
        $pdf->Cell(14, 6, 'Late', 1, 0, 'C', true);
        $pdf->Cell(18, 6, 'Att Rate', 1, 0, 'C', true);
        $pdf->Cell(16, 6, 'Tenders', 1, 0, 'C', true);
        $pdf->Cell(26, 6, 'Total Value (RM)', 1, 1, 'R', true);

