class TBBA_ReportPDF extends FPDF {
    public $reportPeriod = '';
    public $superAdminName = '';

    function Header() {
        // Corporate Header
        $this->SetFont('helvetica', 'B', 15);
        $this->SetTextColor(15, 23, 42); // Navy
        $this->Cell(0, 8, 'THE BRIDGE BUSINESS ALLIANCE (TBBA)', 0, 1, 'C');
        
        $this->SetFont('helvetica', 'B', 10);
        $this->SetTextColor(37, 99, 235); // Enterprise Blue
        $this->Cell(0, 6, 'EXECUTIVE CONSOLIDATED MONTHLY REPORT (ATTENDANCE & TENDER KPI)', 0, 1, 'C');
        
        $this->SetFont('helvetica', '', 9);
        $this->SetTextColor(100, 116, 139);
        $this->Cell(0, 5, 'Reporting Period: ' . $this->reportPeriod . '  |  Generated By: ' . $this->superAdminName, 0, 1, 'C');
        
        // Line break and separator
        $this->Ln(3);
        $this->SetDrawColor(15, 23, 42);
        $this->SetLineWidth(0.6);
        $this->Line(10, $this->GetY(), $this->GetPageWidth() - 10, $this->GetY());
        $this->Ln(6);
    }

    function Footer() {
        $this->SetY(-15);
        $this->SetFont('helvetica', 'I', 8);
        $this->SetTextColor(100, 116, 139);
        $this->Cell(95, 6, 'TBBA Enterprise ERP - Executive Intelligence', 0, 0, 'L');
        $this->Cell(95, 6, 'Page ' . $this->PageNo() . ' of {nb}', 0, 0, 'R');
    }
}

class ReportController {

    public static function index() {
        Auth::requireLogin();
        
        // Restrict strictly to Super Admin or users with system view permissions
        if (!Auth::isSuperAdmin() && !Auth::hasPermission('system', 'view')) {
            Helper::redirect('index.php?page=dashboard&error=unauthorized_report');
            return;
        }

        // Get filter inputs
        $selectedMonth = isset($_GET['month']) ? (int)$_GET['month'] : (int)date('m');
        if ($selectedMonth < 1 || $selectedMonth > 12) $selectedMonth = (int)date('m');
        
        $selectedYear = isset($_GET['year']) ? (int)$_GET['year'] : (int)date('Y');
        if ($selectedYear < 2020 || $selectedYear > 2035) $selectedYear = (int)date('Y');

        $selectedDept = isset($_GET['department_id']) && $_GET['department_id'] !== '' ? (int)$_GET['department_id'] : null;
        
        $monthYearStr = sprintf('%04d-%02d', $selectedYear, $selectedMonth);

        // Fetch all active staff / users
        $userSql = "SELECT id, name, email, role, position, department_id, employee_id, avatar, status 
                    FROM users 
                    WHERE status = 'active' ";
        $userParams = [];
        if ($selectedDept) {
            $userSql .= " AND department_id = ? ";
            $userParams[] = $selectedDept;
        }
        $userSql .= " ORDER BY name ASC";
        $users = Database::query($userSql, $userParams)->fetchAll();

        // Fetch Department map
        $departments = Department::getAll();
        $deptMap = [];
        foreach ($departments as $d) {
            $deptMap[$d['id']] = $d['name'];
        }

        // Fetch all attendance records for selected month & year
        $attRows = Database::query(
            "SELECT id, user_id, date, status, clock_in, clock_out, reason, clock_out_reason 
             FROM attendance 
             WHERE MONTH(date) = ? AND YEAR(date) = ? 
             ORDER BY date ASC, clock_in ASC",
            [$selectedMonth, $selectedYear]
        )->fetchAll();

        // Group attendance by user_id
        $attendanceByUser = [];
        foreach ($attRows as $row) {
            $uid = $row['user_id'];
            if (!isset($attendanceByUser[$uid])) {
                $attendanceByUser[$uid] = [
                    'total_days_worked' => 0,
                    'present_on_time'   => 0,
                    'late'              => 0,
                    'leave_mc_absent'   => 0,
                    'records'           => []
                ];
            }
            $attendanceByUser[$uid]['records'][] = $row;
            $st = strtolower(trim($row['status']));
            if (in_array($st, ['present', 'on_time', 'on time'])) {
                $attendanceByUser[$uid]['present_on_time']++;
                $attendanceByUser[$uid]['total_days_worked']++;
            } elseif ($st === 'late') {
                $attendanceByUser[$uid]['late']++;
                $attendanceByUser[$uid]['total_days_worked']++;
            } else {
                $attendanceByUser[$uid]['leave_mc_absent']++;
            }
        }

        // Fetch all tenders matching this month/year or closing in this month/year
        $tenderRows = Database::query(
            "SELECT t.*, u.name as staff_name, u.position 
             FROM tenders t 
             LEFT JOIN users u ON t.user_id = u.id 
             WHERE t.month_year = ? OR DATE_FORMAT(t.closing_date, '%Y-%m') = ? OR DATE_FORMAT(t.created_at, '%Y-%m') = ? 
             ORDER BY t.closing_date ASC",
            [$monthYearStr, $monthYearStr, $monthYearStr]
        )->fetchAll();

        // Group tenders by user_id
        $tendersByUser = [];
        foreach ($tenderRows as $tRow) {
            $uid = $tRow['user_id'];
            if (!isset($tendersByUser[$uid])) {
                $tendersByUser[$uid] = [
                    'count'       => 0,
                    'total_value' => 0.0,
                    'tenders'     => []
                ];
            }
            $tendersByUser[$uid]['tenders'][] = $tRow;
            $tendersByUser[$uid]['count']++;
            $tendersByUser[$uid]['total_value'] += (float)($tRow['project_value'] ?? 0);
        }

        // Calculate consolidated executive metrics
        $totalStaffCount = count($users);
        $totalTendersCount = count($tenderRows);
        $totalTendersValue = 0.0;
        $totalWonRevenue   = 0.0;
        $totalWonMargin    = 0.0;
        $totalWonCount     = 0;
        foreach ($tenderRows as $tr) {
            $totalTendersValue += (float)($tr['project_value'] ?? 0);
            $sRawCheck = strtolower(trim($tr['status'] ?? ''));
            if (in_array($sRawCheck, ['won', 'approved'])) {
                $wonSelling = (float)($tr['selling_price'] ?? $tr['project_value'] ?? 0);
                $wonCost    = (float)($tr['cost'] ?? 0);
                $totalWonRevenue += $wonSelling;
                $totalWonMargin  += ($wonSelling - $wonCost);
                $totalWonCount++;
            }
        }

        $totalAttRateSum = 0.0;
        $staffWithAttCount = 0;
        $lateAlertsCount = 0;
        $zeroTenderCount = 0;

        foreach ($users as $u) {
            $uid = $u['id'];
            $att = $attendanceByUser[$uid] ?? ['total_days_worked' => 0, 'present_on_time' => 0, 'late' => 0, 'leave_mc_absent' => 0];
            $tnd = $tendersByUser[$uid] ?? ['count' => 0, 'total_value' => 0.0];

            $totLogged = $att['present_on_time'] + $att['late'] + $att['leave_mc_absent'];
            if ($totLogged > 0) {
                $rate = ($att['present_on_time'] / $totLogged) * 100;
                $totalAttRateSum += $rate;
                $staffWithAttCount++;
            }
            if ($att['late'] >= 3) {
                $lateAlertsCount++;
            }
            if ($tnd['count'] === 0 && !in_array($u['role'], ['super_admin', 'admin', 'hr'])) {
                $zeroTenderCount++;
            }
        }

        $avgAttendanceRate = $staffWithAttCount > 0 ? round($totalAttRateSum / $staffWithAttCount, 1) : 100.0;

        $export = $_GET['export'] ?? '';

        // ── Check if Native PDF Export requested (`export=pdf`) ──
        if ($export === 'pdf') {
            self::exportPdf($selectedMonth, $selectedYear, $users, $attendanceByUser, $tendersByUser, $deptMap, $avgAttendanceRate, $totalTendersValue, $lateAlertsCount, $zeroTenderCount, $tenderRows, $totalWonMargin, $totalWonRevenue, $totalWonCount);
            return;
        }

        // ── Check if Standalone Formal Document View requested (`export=print`) ──
        if ($export === 'print') {
            include __DIR__ . '/../views/reports/print.php';
            return;
        }

        // ── Check if CSV Export requested (`export=csv`) ──
        if ($export === 'csv') {
            self::exportCsv($selectedMonth, $selectedYear, $users, $attendanceByUser, $tendersByUser, $deptMap);
            return;
        }

        $pageTitle = 'Monthly Reports';
        include __DIR__ . '/../views/reports/index.php';
    }

