                $pdf->Cell(22, 6, $valStr, 1, 0, 'R');

                // Margin cell: green if positive, red if negative
                if ($hasMargin) {
                    if ($rowMargin >= 0) $pdf->SetTextColor(5, 150, 105);
                    else $pdf->SetTextColor(220, 38, 38);
                } else {
                    $pdf->SetTextColor(148, 163, 184);
                }
                $pdf->Cell(22, 6, $marginStr, 1, 0, 'R');
