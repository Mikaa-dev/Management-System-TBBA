        // Spacing for physical signature
        $pdf->Ln(14);
        $yLine = $pdf->GetY();
        
        // Row 2: Signature Lines
        $pdf->SetDrawColor(15, 23, 42);
        $pdf->Line(10, $yLine, 95, $yLine);
        $pdf->Line(110, $yLine, 195, $yLine);
        $pdf->Ln(2);
        
        // Row 3: Names
        $pdf->SetFont('helvetica', 'B', 9);
        $pdf->SetTextColor(15, 23, 42);
        $pdf->Cell(90, 5, $pdf->superAdminName, 0, 0, 'L');
        $pdf->Cell(10, 5, '', 0, 0, 'C');
        $pdf->Cell(90, 5, 'Managing Director / Chief Executive Officer', 0, 1, 'L');
        
        // Row 4: Roles
        $pdf->SetFont('helvetica', '', 8);
        $pdf->SetTextColor(100, 116, 139);
        $pdf->Cell(90, 4, 'Super Administrator / HR Management', 0, 0, 'L');
        $pdf->Cell(10, 4, '', 0, 0, 'C');
        $pdf->Cell(90, 4, 'The Bridge Business Alliance (TBBA)', 0, 1, 'L');
        
        // Row 5: Dates
        $pdf->Cell(90, 4, 'Date: ' . date('d M Y'), 0, 0, 'L');
        $pdf->Cell(10, 4, '', 0, 0, 'C');
        $pdf->Cell(90, 4, 'Date: ________________________', 0, 1, 'L');

        // Output binary PDF to download
        $pdf->Output('D', "TBBA_Executive_Report_{$monthName}_{$year}.pdf");
        exit;
    }

    // Export complete report to CSV
    private static function exportCsv($month, $year, $users, $attendanceByUser, $tendersByUser, $deptMap) {
        $monthName = date('F', mktime(0, 0, 0, $month, 1, $year));
        $filename  = "TBBA_Executive_Report_{$monthName}_{$year}.csv";

        header('Content-Type: text/csv; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Pragma: no-cache');
        header('Expires: 0');

        $output = fopen('php://output', 'w');

        // Title Header
        self::writeCsvRow($output, ['THE BRIDGE BUSINESS ALLIANCE (TBBA)']);
        self::writeCsvRow($output, ["EXECUTIVE CONSOLIDATED MONTHLY REPORT - {$monthName} {$year}"]);
        self::writeCsvRow($output, ['Generated on:', date('Y-m-d H:i:s')]);
        self::writeCsvRow($output, []);

        // Table 1: Staff Attendance & KPI Summary
        self::writeCsvRow($output, ['SECTION 1: STAFF ATTENDANCE & TENDER KPI SUMMARY']);
        self::writeCsvRow($output, [
            'Staff ID',
            'Staff Name',
            'Role',
            'Position',
            'Department',
            'Present / On-Time (Days)',
            'Late (Days)',
            'Leave / MC / Absent (Days)',
            'Attendance Rate (%)',
            'Tenders Submitted',
            'Total Tender Value (RM)'
        ]);

        foreach ($users as $u) {
            $uid = $u['id'];
            $att = $attendanceByUser[$uid] ?? ['present_on_time' => 0, 'late' => 0, 'leave_mc_absent' => 0];
            $tnd = $tendersByUser[$uid] ?? ['count' => 0, 'total_value' => 0.0];

            $totLogged = $att['present_on_time'] + $att['late'] + $att['leave_mc_absent'];
            $rateStr = $totLogged > 0 ? round(($att['present_on_time'] / $totLogged) * 100, 1) . '%' : 'N/A';

            self::writeCsvRow($output, [
                $u['employee_id'] ?: 'TBBA-'.str_pad($u['id'], 4, '0', STR_PAD_LEFT),
                $u['name'],
                strtoupper($u['role']),
                $u['position'] ?: '-',
                $deptMap[$u['department_id'] ?? 0] ?? '-',
                $att['present_on_time'],
                $att['late'],
                $att['leave_mc_absent'],
                $rateStr,
                $tnd['count'],
                number_format($tnd['total_value'], 2, '.', '')
            ]);
        }

        self::writeCsvRow($output, []);
        self::writeCsvRow($output, []);

        // Table 2: Detailed Tender List for the Month
        self::writeCsvRow($output, ['SECTION 2: MONTHLY TENDER & PROJECT SUBMISSION DETAILS']);
        self::writeCsvRow($output, [
            'Tender ID',
            'Staff In Charge',
            'Project Name',
            'Client Name',
            'Closing Date',
            'Project Value (RM)',
            'Cost (RM)',
            'Selling Price (RM)',
            'Margin / Profit (RM)',
            'Status'
        ]);

        foreach ($users as $u) {
            $uid = $u['id'];
            if (isset($tendersByUser[$uid]['tenders'])) {
                foreach ($tendersByUser[$uid]['tenders'] as $tRow) {
                    $csvSelling = $tRow['selling_price'] !== null ? (float)$tRow['selling_price'] : null;
                    $csvCost    = $tRow['cost'] !== null ? (float)$tRow['cost'] : null;
                    $csvMargin  = ($csvSelling !== null && $csvCost !== null) ? $csvSelling - $csvCost : null;
                    self::writeCsvRow($output, [
                        'TND-'.str_pad($tRow['id'], 4, '0', STR_PAD_LEFT),
                        $u['name'],
                        $tRow['project_name'],
                        $tRow['client_name'],
                        $tRow['closing_date'],
                        number_format((float)($tRow['project_value'] ?? 0), 2, '.', ''),
                        $csvCost !== null ? number_format($csvCost, 2, '.', '') : '',
                        $csvSelling !== null ? number_format($csvSelling, 2, '.', '') : '',
                        $csvMargin !== null ? number_format($csvMargin, 2, '.', '') : '',
                        strtoupper($tRow['status'])
                    ]);
                }
            }
        }

        fclose($output);
        exit;
    }

    private static function writeCsvRow($output, array $fields): void {
        $safeFields = array_map(static function ($value) {
            if (!is_string($value)) return $value;
            $value = str_replace("\0", '', $value);
            return preg_match('/^[\\x00-\\x20]*[=+\\-@]/', $value) ? "'" . $value : $value;
        }, $fields);
        fputcsv($output, $safeFields, ',', '"', '');
    }
