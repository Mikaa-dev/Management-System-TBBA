        $pdf->SetTextColor(15, 23, 42);
        $pdf->Cell(0, 6, 'SECTION 1: PERSONNEL ATTENDANCE & TENDER KPI SCORECARD', 0, 1, 'L');
        $pdf->Ln(1);

        $pdf->SetFont('helvetica', 'B', 8);
        $pdf->SetFillColor(241, 245, 249);
        $pdf->SetDrawColor(203, 213, 225);
        $pdf->SetTextColor(15, 23, 42);
        
